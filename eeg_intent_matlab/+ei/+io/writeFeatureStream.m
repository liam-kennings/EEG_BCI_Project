function writeFeatureStream(stream, filePath)
%WRITEFEATURESTREAM Save a feature stream to HDF5 (readable from MATLAB and Python).
%   ei.io.writeFeatureStream(stream, filePath)
%   Arrays are written in MATLAB order, e.g. /log_power is [rows x channels x bands].
%   h5py reads HDF5 dimensions in reverse, so Python sees [bands x channels x rows];
%   the attribute "matlab_dimension_order" records this.

    arguments
        stream (1,1) struct
        filePath (1,1) string
    end

    if isfile(filePath)
        delete(filePath);
    end
    datasets = struct( ...
        "time_seconds", stream.Time, ...
        "log_power", stream.LogPower, ...
        "log_power_drift", stream.LogPowerDrift, ...
        "broadband_rms_uv", stream.BroadbandRms, ...
        "artifact", stream.Artifact, ...
        "is_filter_warm", double(stream.IsFilterWarm), ...
        "is_drift_warm", double(stream.IsDriftWarm));
    names = string(fieldnames(datasets))';
    for name = names
        values = datasets.(name);
        h5create(filePath, "/" + name, size(values), Datatype="double");
        h5write(filePath, "/" + name, values);
    end
    attributes = struct( ...
        "channel_labels", strjoin(stream.Labels, ","), ...
        "band_names", strjoin(stream.BandNames, ","), ...
        "artifact_names", strjoin(stream.ArtifactNames, ","), ...
        "is_good_channel", strjoin(string(double(stream.IsGood)), ","), ...
        "sampling_rate_hz", stream.Fs, ...
        "feature_rate_hz", stream.FeatureRateHz, ...
        "source", stream.Source, ...
        "config_sha256", stream.ConfigSha256, ...
        "git_commit", ei.util.gitCommit(), ...
        "matlab_dimension_order", "log_power: [rows x channels x bands]");
    for name = string(fieldnames(attributes))'
        h5writeatt(filePath, "/", name, attributes.(name));
    end
end
